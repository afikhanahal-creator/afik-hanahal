test('positives are classified as real estate', () => {
  const miss = POS.filter(t => !scoreRealEstate(t).ok).map(t => `${t}  →  ${JSON.stringify(scoreRealEstate(t))}`)
  assert.deepEqual(miss, [], `false negatives:\n  ${miss.join('\n  ')}`)
})

test('negatives are rejected', () => {
  const leak = NEG.filter(t => scoreRealEstate(t).ok).map(t => `${t}  →  ${JSON.stringify(scoreRealEstate(t))}`)
  assert.deepEqual(leak, [], `false positives:\n  ${leak.join('\n  ')}`)
})

test('description rescues a weak title', () => {
  assert.equal(scoreRealEstate('ההחלטה שתשנה את השרון', 'הוועדה המחוזית אישרה 3,000 יח"ד בכפר סבא').ok, true)
})

test('veto in description does not override a clear title', () => {
  assert.equal(scoreRealEstate('מחירי הדירות בצפון בעקבות המלחמה', 'טילים מלבנון פגעו בבניינים').ok, true)
})

test('trusted feed relaxes corroboration but not veto', () => {
  assert.equal(scoreRealEstate('הדירה של השבוע', '', { trusted: true }).ok, true)
  assert.equal(scoreRealEstate('צעיר נמצא מת בדירה', '', { trusted: true }).ok, false)
})

test('hebrew quote variants normalise', () => {
  for (const t of ['נדל״ן בשרון: מחירים חדשים', "נדל'ן בשרון: מחירים חדשים", 'נדלן בשרון: מחירים חדשים', 'נדל"ן בשרון: מחירים חדשים'])
    assert.equal(scoreRealEstate(t).ok, true, t)
})
